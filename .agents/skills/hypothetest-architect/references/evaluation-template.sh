# ----- Process command line arguments -----

if [[ $# -gt 0 ]]; then
    command="${1}" && shift
fi

if [[ ! ${command} =~ ^(run|report|plan|env|help|-?-?h(elp)?)$ ]]; then
    log_error "Invalid command $(magenta "${command}")"
    print_help_main
    exit 1
fi

while [[ $# -gt 0 ]]; do
    case "$1" in
        -d|--debug)
            export LOG_LEVEL="debug"
            shift
        ;;
        -e|--env)
            shift
            if [[ $# -eq 0 ]]; then
                log_error "Missing environment filename"
                exit 1
            fi
            env_file="${1}"
            shift
        ;;
        -n|--dry-run)
            export HYPOTHETEST_DRY_RUN="true"
            shift
        ;;
        -q|--quiet)
            quiet="true"
            shift
        ;;
        -o|--output)
            shift
            if [[ $# -eq 0 ]]; then
                log_error "Missing output directory"
                exit 1
            fi
            export HYPOTHETEST_EVALUATION_ROOT="${1}"
            shift
        ;;
        -r|--run-id)
            shift
            if [[ $# -eq 0 ]]; then
                log_error "Missing run id"
                exit 1
            fi
            export HYPOTHETEST_RUN_ID="${1}"
            shift
        ;;
        --keep-going)
            keep_going="true"
            shift
        ;;
        --no-color)
            colorize=false
            shift
        ;;
        --version)
            echo "${template_version}"
            exit 0
        ;;
        *)
            log_error "Unknown option $(magenta "${1}")"
            print_usage
            exit 1
        ;;
    esac
done

env_file_source
environment_setup
log_debug "Input command: $(white "${command}")"
log_debug "Keep going: $(cyan "${keep_going}")"

case "${command}" in
    "help"|"-h"|"--help" )
        print_help_main
    ;;
    "plan" )
        print_plan
    ;;
    "env" )
        print_env
    ;;
    "run" )
        command_run
    ;;
    "report" )
        command_report
    ;;
esac
