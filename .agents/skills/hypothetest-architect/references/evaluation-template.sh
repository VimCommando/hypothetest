#!/usr/bin/env bash

# Hypothetest evaluation runner template.
#
# The Architect copies this file to generated/scripts/evaluation.sh and replaces
# the placeholder task sequence and task functions with the deterministic plan
# compiled from hypothetest.yml. Keep this script portable: it should run with
# the system bash on macOS and Linux.

set -Eeuo pipefail

# ----- Logging Functions -----

declare log_name="hypothetest-evaluation"
declare colorize=false
if [[ -t 1 ]]; then
    colorize=true
fi

function echo_color() {
    local color=$1; shift
    if [[ $colorize == true ]]; then
        printf "\033[%sm%b\033[39m" "${color}" "${*}"
    else
        printf "%b" "${*}"
    fi
}

function red()       { echo_color 31 "${@}"; }
function green()     { echo_color 32 "${@}"; }
function yellow()    { echo_color 33 "${@}"; }
function blue()      { echo_color 34 "${@}"; }
function magenta()   { echo_color 35 "${@}"; }
function cyan()      { echo_color 36 "${@}"; }
function gray()      { echo_color 90 "${@}"; }
function white()     { echo_color 97 "${@}"; }

function timestamp() { date -u +"%Y-%m-%d %H:%M:%S"; }
function log_error() { echo "[$(timestamp) $(red Error) ${log_name}] ${*}"; }
function log_warn()  { echo "[$(timestamp) $(yellow Warn)  ${log_name}] ${*}"; }
function log_info() {
    if [[ ${quiet} == "true" ]]; then return 0; fi
    echo "[$(timestamp) $(green Info)  ${log_name}] ${*}"
}
function log_debug() {
    if [[ ${quiet} == "true" ]]; then return 0; fi
    if [[ ${LOG_LEVEL:-info} == "debug" ]]; then
        echo "[$(timestamp) $(blue Debug) ${log_name}] ${*}"
    fi
}
function log_milestone() {
    echo "[$(timestamp) $(cyan Mile)  ${log_name}] ${*}"
}

# ----- Help Functions -----

function print_usage() {
    echo "$(white "Usage:") evaluation.sh <command> [options]"
}

function print_help_main() {
    white "Description:\n"
    echo "    Deterministic Hypothetest evaluation runner generated by the Architect."
    echo
    white "Usage:\n"
    echo "    $(green ./generated/scripts/evaluation.sh) <command> [options]"
    echo
    white "Commands:\n"
    echo "    $(green run)       Execute the compiled evaluation plan"
    echo "    $(green report)    Regenerate comparison and report from existing measurements"
    echo "    $(green plan)      Print the generated task plan"
    echo "    $(green env)       Print resolved environment configuration"
    echo "    $(green help)      Print help for this script"
    echo
    white "Options:\n"
    echo "    -e, --env <FILE>       Source environment variables from FILE"
    echo "    -o, --output <DIR>     Evaluation output root"
    echo "    -r, --run-id <ID>      Stable run identifier"
    echo "    -n, --dry-run          Print commands without executing task bodies"
    echo "    -d, --debug            Enable debug logging"
    echo "    -q, --quiet            Suppress info/debug output; show milestones and errors only"
    echo "        --keep-going       Continue independent task groups after failures"
    echo "        --no-color         Disable colorized output"
    echo "        --version          Print template version"
    echo
    white "Environment Variables:\n"
    echo "    HYPOTHETEST_PLAN              Path to hypothetest.yml"
    echo "    HYPOTHETEST_EVALUATION_ROOT   Directory for evaluation artifacts"
    echo "    HYPOTHETEST_RUN_ID            Run id, defaults to UTC timestamp"
    echo "    HYPOTHETEST_DRY_RUN           true or false"
    echo "    LOG_LEVEL                     info or debug"
    echo
}

# ----- Environment Configuration -----

declare template_version="0.2.0"
declare script_dir
script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
declare blueprint_root
blueprint_root="$(cd "${script_dir}/../.." && pwd)"

declare env_file=""
declare command="run"
declare keep_going="false"
declare quiet="false"

export LOG_LEVEL="${LOG_LEVEL:-info}"
export HYPOTHETEST_PLAN="${HYPOTHETEST_PLAN:-${blueprint_root}/hypothetest.yml}"
export HYPOTHETEST_EVALUATION_ROOT="${HYPOTHETEST_EVALUATION_ROOT:-${blueprint_root}/evaluations}"
export HYPOTHETEST_RUN_ID="${HYPOTHETEST_RUN_ID:-$(date -u +%Y%m%dT%H%M%SZ)}"
export HYPOTHETEST_DRY_RUN="${HYPOTHETEST_DRY_RUN:-false}"

function env_file_source() {
    if [[ -z ${env_file} ]]; then
        return 0
    fi
    if [[ ! -f ${env_file} ]]; then
        log_error "Environment file $(magenta "${env_file}") not found"
        exit 1
    fi
    log_debug "Sourcing $(gray "${env_file}")"
    # shellcheck disable=SC1090
    source "${env_file}"
}

function environment_setup() {
    export HYPOTHETEST_EVALUATION_DIR="${HYPOTHETEST_EVALUATION_ROOT}/${HYPOTHETEST_RUN_ID}"
    export HYPOTHETEST_EVIDENCE_DIR="${HYPOTHETEST_EVALUATION_DIR}/evidence"
    export HYPOTHETEST_RAW_DIR="${HYPOTHETEST_EVIDENCE_DIR}/raw"
    export HYPOTHETEST_PHASE_OUTPUT_DIR="${HYPOTHETEST_EVIDENCE_DIR}/phase-output"
    export HYPOTHETEST_DIAGNOSTICS_DIR="${HYPOTHETEST_EVIDENCE_DIR}/diagnostics"
    export HYPOTHETEST_LOG_DIR="${HYPOTHETEST_EVALUATION_DIR}/logs"
    export HYPOTHETEST_MEASUREMENTS_DIR="${HYPOTHETEST_EVALUATION_DIR}/measurements"
    export HYPOTHETEST_COMPARISONS_DIR="${HYPOTHETEST_EVALUATION_DIR}/comparisons"
}

function print_env() {
    echo "HYPOTHETEST_PLAN=${HYPOTHETEST_PLAN}"
    echo "HYPOTHETEST_EVALUATION_ROOT=${HYPOTHETEST_EVALUATION_ROOT}"
    echo "HYPOTHETEST_RUN_ID=${HYPOTHETEST_RUN_ID}"
    echo "HYPOTHETEST_EVALUATION_DIR=${HYPOTHETEST_EVALUATION_DIR}"
    echo "HYPOTHETEST_DRY_RUN=${HYPOTHETEST_DRY_RUN}"
    echo "LOG_LEVEL=${LOG_LEVEL}"
}

# ----- Process Control -----

declare current_task=""

function on_error() {
    local status=$?
    if [[ -n ${current_task} ]]; then
        log_error "Task $(magenta "${current_task}") failed with exit status ${status}"
    else
        log_error "Evaluation failed with exit status ${status}"
    fi
    exit "${status}"
}

trap on_error ERR

function ensure_directories() {
    mkdir -p \
        "${HYPOTHETEST_RAW_DIR}" \
        "${HYPOTHETEST_PHASE_OUTPUT_DIR}" \
        "${HYPOTHETEST_DIAGNOSTICS_DIR}" \
        "${HYPOTHETEST_LOG_DIR}" \
        "${HYPOTHETEST_MEASUREMENTS_DIR}" \
        "${HYPOTHETEST_COMPARISONS_DIR}"
}

function run_cmd() {
    log_info "$(green running) $(white "$*")"
    if [[ ${HYPOTHETEST_DRY_RUN} == "true" ]]; then
        return 0
    fi
    "$@"
}

function task_function_name() {
    local task="${1//-/_}"
    echo "task_${task}"
}

function run_task() {
    local task="$1"
    local fn
    fn="$(task_function_name "${task}")"
    if ! declare -f "${fn}" >/dev/null; then
        log_error "Task function $(magenta "${fn}") is not defined"
        return 1
    fi

    current_task="${task}"
    log_info "$(green start) task $(cyan "${task}")"
    if [[ ${HYPOTHETEST_DRY_RUN} == "true" ]]; then
        log_info "$(yellow dry-run) task $(cyan "${task}") would execute $(white "${fn}")"
    else
        "${fn}" > "${HYPOTHETEST_LOG_DIR}/${task}.log" 2>&1
    fi
    log_info "$(green complete) task $(cyan "${task}")"
    current_task=""
}

function run_parallel() {
    local tasks=("$@")
    local pids=()
    local failed=0
    local index=0

    log_info "$(green start) parallel group: $(cyan "${tasks[*]}")"
    for task in "${tasks[@]}"; do
        (
            run_task "${task}"
        ) &
        pids[index]=$!
        index=$((index + 1))
    done

    index=0
    for task in "${tasks[@]}"; do
        if ! wait "${pids[$index]}"; then
            failed=1
            log_error "Parallel task $(magenta "${task}") failed"
        fi
        index=$((index + 1))
    done

    if [[ ${failed} -ne 0 && ${keep_going} == "true" ]]; then
        log_warn "Parallel group failed, continuing because $(gray --keep-going) is set"
        return 0
    elif [[ ${failed} -ne 0 ]]; then
        return 1
    fi
    log_info "$(green complete) parallel group"
}

# ----- Generated Evaluation Plan -----

function print_plan() {
    cat <<'PLAN'
Generated task plan:
  1. validate_prerequisites
  2. prepare_workspace
  3. setup_baseline
  4. reset_baseline
  5. load_baseline_dataset
  6. parallel: collect_baseline_before, capture_baseline_environment
  7. run_baseline_workload
  8. collect_baseline_after
  9. setup_candidate
 10. reset_candidate
 11. load_candidate_dataset
 12. parallel: collect_candidate_before, capture_candidate_environment
 13. run_candidate_workload
 14. collect_candidate_after
 15. compare_results
 16. write_report
PLAN
}

function command_run() {
    ensure_directories
    print_env > "${HYPOTHETEST_EVALUATION_DIR}/evaluation.env"
    cp "${HYPOTHETEST_PLAN}" "${HYPOTHETEST_EVALUATION_DIR}/hypothetest.yml"

    run_task validate_prerequisites
    run_task prepare_workspace

    run_task setup_baseline
    run_task reset_baseline
    run_task load_baseline_dataset
    run_parallel collect_baseline_before capture_baseline_environment
    run_task run_baseline_workload
    run_task collect_baseline_after

    run_task setup_candidate
    run_task reset_candidate
    run_task load_candidate_dataset
    run_parallel collect_candidate_before capture_candidate_environment
    run_task run_candidate_workload
    run_task collect_candidate_after

    run_task compare_results
    run_task write_report
    log_info "$(green complete) evaluation artifacts at $(cyan "${HYPOTHETEST_EVALUATION_DIR}")"
}

function command_report() {
    if [[ ! -d ${HYPOTHETEST_EVALUATION_DIR} ]]; then
        log_error "Evaluation directory $(magenta "${HYPOTHETEST_EVALUATION_DIR}") not found"
        log_error "Use $(white "--run-id <ID>") to specify the evaluation to regenerate"
        exit 1
    fi
    log_milestone "Regenerating report for $(cyan "${HYPOTHETEST_RUN_ID}")"
    run_task compare_results
    run_task write_report
    log_milestone "Report artifacts updated at $(cyan "${HYPOTHETEST_EVALUATION_DIR}")"
}

# ----- Generated Task Functions -----

